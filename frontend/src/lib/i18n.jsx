const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => (
    localStorage.getItem(LANGUAGE_KEY) === "hi" ? "hi" : "en"
  ));

  const setLanguage = useCallback((nextLanguage) => {
    if (nextLanguage !== "en" && nextLanguage !== "hi") {
      throw new Error(`Unsupported language: ${nextLanguage}`);
    }
    setLanguageState(nextLanguage);
  }, []);

  useEffect(() => {
    localStorage.setItem(LANGUAGE_KEY, language);
    document.documentElement.lang = language;
    document.title = language === "hi"
      ? hindi["SaafHisaab Mandi | Har hisaab, saaf saaf"]
      : "SaafHisaab Mandi | Clear accounts, the simple way";
  }, [language]);

  const t = useCallback((text) => (
    language === "hi" ? hindi[text] || text : text
  ), [language]);

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useTranslation() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useTranslation must be used within a LanguageProvider");
  }
  return context;
}
